import { useMutation } from "@tanstack/react-query";
import { Loader2, Send, Sparkles } from "lucide-react";
import { useRef, useState } from "react";
import { api, ApiError } from "../../../api/client";
import type { CopilotAnswer } from "../../../api/types";
import { Badge } from "../../../components/ui/badge";
import { Button } from "../../../components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "../../../components/ui/card";
import { Input } from "../../../components/ui/input";

const SUGGESTIONS = [
  "How much revenue did we collect this month?",
  "What is our current MRR and ARR?",
  "Which customers have the highest outstanding balances?",
  "How many invoices are overdue?",
  "Which subscriptions are due for renewal next month?",
  "Which subscription plans generate the most recurring revenue?",
  "What are our biggest financial risks?",
  "What collections do we forecast for next month?",
];

interface ChatTurn {
  question: string;
  answer: CopilotAnswer | null;
  error: string | null;
}

export default function CopilotPanel() {
  const [question, setQuestion] = useState("");
  const [turns, setTurns] = useState<ChatTurn[]>([]);
  const bottomRef = useRef<HTMLDivElement>(null);

  const ask = useMutation({
    mutationFn: (q: string) =>
      api<CopilotAnswer>("/finance-intelligence/copilot", {
        method: "POST",
        body: JSON.stringify({ question: q }),
      }),
    onSuccess: (data, q) => {
      setTurns((t) => [
        ...t,
        { question: q, answer: data, error: null },
      ]);
      setTimeout(() => bottomRef.current?.scrollIntoView({ behavior: "smooth" }), 50);
    },
    onError: (err, q) => {
      const e = err as ApiError;
      setTurns((t) => [
        ...t,
        {
          question: q,
          answer: null,
          error:
            e.code === "RATE_LIMITED"
              ? "Rate limited — wait a minute and retry."
              : e.message || "Copilot request failed.",
        },
      ]);
    },
  });

  function submit(q: string) {
    const trimmed = q.trim();
    if (!trimmed || ask.isPending) return;
    setQuestion("");
    ask.mutate(trimmed);
  }

  return (
    <div className="grid gap-6 lg:grid-cols-[1fr_260px]">
      <Card className="flex min-h-[480px] flex-col">
        <CardHeader>
          <CardTitle className="flex items-center gap-2">
            <Sparkles className="h-4 w-4" />
            Finance Copilot
            <span className="text-xs font-normal text-cream0">
              answers grounded in verified backend metrics
            </span>
          </CardTitle>
        </CardHeader>
        <CardContent className="flex flex-1 flex-col">
          <div className="flex-1 space-y-4 overflow-y-auto pb-4">
            {turns.length === 0 && (
              <p className="py-8 text-center text-sm text-cream0">
                Ask a question about revenue, collections, MRR/ARR, outstanding
                balances, renewals or financial risks. Every figure comes from
                the analytics services — never generated by the model.
              </p>
            )}
            {turns.map((turn, i) => (
              <div key={i} className="space-y-2">
                <div className="flex justify-end">
                  <p className="max-w-[80%] rounded-lg bg-ink px-3 py-2 text-sm text-cream-card">
                    {turn.question}
                  </p>
                </div>
                <div className="flex justify-start">
                  <div className="max-w-[85%] rounded-lg border border-line bg-cream-card px-3 py-2 text-sm">
                    {turn.answer ? (
                      <>
                        <p className="whitespace-pre-wrap text-ink">
                          {turn.answer.answer}
                        </p>
                        <div className="mt-2 flex flex-wrap items-center gap-1.5 border-t border-sage-faint pt-2">
                          <Badge variant="secondary">{turn.answer.intent}</Badge>
                          <Badge variant="outline">
                            {turn.answer.provider}
                            {turn.answer.model ? ` · ${turn.answer.model}` : ""}
                          </Badge>
                          {turn.answer.sources.map((s) => (
                            <Badge key={s} variant="outline" className="text-cream0">
                              {s}
                            </Badge>
                          ))}
                        </div>
                      </>
                    ) : (
                      <p className="text-danger">{turn.error}</p>
                    )}
                  </div>
                </div>
              </div>
            ))}
            {ask.isPending && (
              <div className="flex items-center gap-2 text-sm text-cream0">
                <Loader2 className="h-4 w-4 animate-spin" />
                Gathering verified metrics…
              </div>
            )}
            <div ref={bottomRef} />
          </div>

          <form
            className="flex gap-2 border-t border-sage-faint pt-3"
            onSubmit={(e) => {
              e.preventDefault();
              submit(question);
            }}
          >
            <Input
              value={question}
              onChange={(e) => setQuestion(e.target.value)}
              placeholder="Ask about revenue, MRR, outstanding, renewals…"
              maxLength={1000}
            />
            <Button type="submit" disabled={ask.isPending || !question.trim()}>
              <Send className="h-4 w-4" />
            </Button>
          </form>
        </CardContent>
      </Card>

      <Card>
        <CardHeader>
          <CardTitle className="text-xs font-medium uppercase tracking-wide text-cream0">
            Suggested questions
          </CardTitle>
        </CardHeader>
        <CardContent className="space-y-2">
          {SUGGESTIONS.map((s) => (
            <button
              key={s}
              type="button"
              onClick={() => submit(s)}
              disabled={ask.isPending}
              className="block w-full rounded-md border border-line px-3 py-2 text-left text-sm text-ink hover:bg-cream disabled:opacity-50"
            >
              {s}
            </button>
          ))}
        </CardContent>
      </Card>
    </div>
  );
}
